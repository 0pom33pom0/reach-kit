from . import ytdlp

NAME = "youtube"
HOSTS = ("youtube.com", "youtu.be", "youtube-nocookie.com")


def match(url: str) -> bool:
    host = (urllib.parse.urlsplit(url).hostname or "").lower()
    return any(host == h or host.endswith("." + h) for h in HOSTS)


def _comment_args(opts: Options) -> str:
    replies = 5 if opts.depth > 1 else 0
    sort = "new" if opts.sort == "new" else "top"
    return f"youtube:max_comments=all,{opts.limit},{opts.limit * replies},{replies};comment_sort={sort}"


def read(url: str, opts: Options) -> Result:
    data = ytdlp.info(url, opts, comments=opts.comments,
                      extractor_args=_comment_args(opts) if opts.comments else None)
    return ytdlp.to_result(data, NAME, url, opts)


# ---- transcript -------------------------------------------------------------

def _match_lang(tracks: dict, lang: str) -> Optional[str]:
    if lang in tracks:
        return lang
    base = lang.split("-")[0].lower()
    for key in tracks:
        if key.split("-")[0].lower() == base and not key.endswith("-orig"):
            return key
    return None


def pick_track(data: dict, wanted: List[str]) -> Tuple[str, str, List[str]]:
    """Choose a subtitle track. Returns (kind, key, warnings).

    Prefers human-made subtitles in the original or requested language; only
    then auto-generated ones, and always says so — a machine translation is
    never passed off as the speaker's words.
    """
    manual = {k: v for k, v in (data.get("subtitles") or {}).items() if k != "live_chat"}
    auto = data.get("automatic_captions") or {}
    orig = data.get("language")
    candidates = list(wanted) or ([orig] if orig else [])

    for lang in candidates:
        key = _match_lang(manual, lang)
        if key:
            return "manual", key, []
    if not candidates and manual:
        return "manual", next(iter(manual)), []

    orig_auto = next((k for k in auto if k.endswith("-orig")), None)
    if orig_auto is None and orig and orig in auto:
        orig_auto = orig
    if orig_auto and (not wanted or any(orig_auto.split("-")[0] == w.split("-")[0] for w in wanted)):
        return "auto", orig_auto, ["subtitles are auto-generated by YouTube speech recognition (may contain errors)"]

    for lang in candidates:
        key = _match_lang(auto, lang)
        if key:
            return "auto", key, [
                f"no human subtitles in '{lang}': using YouTube auto captions "
                "(auto-generated and possibly MACHINE-TRANSLATED from another language)"
            ]
    if manual:
        key = next(iter(manual))
        return "manual", key, [f"requested language not available; using human subtitles in '{key}'"]
    if orig_auto:
        return "auto", orig_auto, ["requested language not available; using auto-generated original-language captions"]
    available = sorted(set(manual) | {k for k in auto if k.endswith("-orig")})
    raise ReachError("not_found", "this video has no usable subtitles",
                     f"available tracks: {', '.join(available) or 'none'}")


def json3_to_text(payload: dict) -> str:
    lines: List[str] = []
    for ev in payload.get("events") or []:
        segs = ev.get("segs") or []
        line = "".join(s.get("utf8", "") for s in segs).replace("\n", " ").strip()
        if line and (not lines or lines[-1] != line):
            lines.append(line)
    return clean("\n".join(lines))


def transcript(url: str, opts: Options) -> Result:
    data = ytdlp.info(url, opts)
    kind, key, warnings = pick_track(data, opts.lang)
    tracks = (data.get("subtitles") if kind == "manual" else data.get("automatic_captions")) or {}
    fmt = next((f for f in tracks.get(key, []) if f.get("ext") == "json3"), None)
    if not fmt:
        raise ReachError("parse_error", f"subtitle track '{key}' has no json3 format")
    payload = net.http_get(fmt["url"], timeout=opts.timeout, browser=True).json()
    r = ytdlp.to_result(data, NAME, url, Options(comments=False))
    r.text = json3_to_text(payload)
    r.stats = {"duration_s": r.stats.get("duration_s"), "subtitle_lang": key, "subtitle_kind": kind}
    r.warnings.extend(warnings)
    r.source = f"yt-dlp + youtube timedtext ({kind}:{key})"
    return r

